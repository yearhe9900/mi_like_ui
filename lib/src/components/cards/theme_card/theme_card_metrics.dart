/// [MiThemeCard] 的几何与文字规格（设计度量，393dp 设计宽）。
///
/// 规格取自 881×1920 参考素材（1220×2656 等比副本，亮色），
/// 换算系数 s = 393 / 881 = 0.4461：
///
/// | 项目                  | 素材 px | dp            |
/// |-----------------------|---------|---------------|
/// | 预览图宽 × 高（3 列） | 259 x 472 | 115.5 x 210.6 |
/// | 预览图圆角（圆弧拟合）| R = 44  | 19.6          |
/// | 列间距                | 26.5    | 11.9          |
/// | 页面边距              | 25~28   | 11.9          |
/// | 标题字号（CJK em）    | 31      | 13.85         |
/// | 标题相对图左缘内缩    | 19.5    | 8.8           |
/// | 图底 → 标题墨迹       | 19      | 8*            |
/// | 标题 → 次行图         | 35      | 15*           |
/// | 行距（图顶 → 图顶）   | 554     | 247           |
///
/// \* 墨迹 → 行盒换算：`height: 1.0` 行盒 = 字号（31px 字面 / 28px 墨迹，
/// 上下留白对称各 ≈1.5px），扣留白后取整。
///
/// 说明：
///
///  * 预览图固定宽高比 259:472（高 = 宽 / 比值，宽随父级），圆角取
///    [previewRadius]（12.9，实机修订值，见其注记）；
///  * 标题相对图片左缘内缩（多卡一致、与区块标题同列），为左对齐 + 内缩，
///    非居中；
///  * 页面文本列 ≈20.5dp、卡片图区页边距 11.9dp，标题内缩 8.8dp 使两者
///    起排列对齐；
///  * 标签字重 Medium、单行省略。
///
/// 文字样式见 `theme/typography.dart`（[MiTypography.cardTitle]）；标题
/// 墨色经 `MiColors.foregroundFor(mode)` 取框架前景色，无独立配色 token。
class MiThemeCardMetrics {
  MiThemeCardMetrics._();

  /// 预览图宽高比 = 259:472 ≈ 0.549（度量 3 列卡图 259x472px）。
  static const double imageAspectRatio = 259 / 472;

  /// 预览图圆角 **12.9dp**（**度量修订**，2026-10-28 实机截图）。
  ///
  /// 旧值 20（881×1920 早期素材圆弧拟合 R = 44）疑为旧版卡型外推；
  /// 实机主题商店页截图（1220×2656）双测点比例换算：3 列卡角弧比
  /// 0.101（带宽 0.088…0.115 → 10.2…13.3dp）、2 列卡 0.079
  ///（→ 12.1…16.0dp），交叠带 [12.1, 13.3] 取中 **12.9**
  ///（= 881 素材口径 29px）。
  static const double previewRadius = 12.9;

  /// 标题相对图片左缘的内缩（度量 19~20px 三卡一致，取中 8.8dp）。
  static const double titleIndent = 8.8;

  /// 图片底 -> 标题行盒（度量墨迹 19px ≈ 8.5dp，扣字形上留白 ≈7.8dp，
  /// 取 8 ≈ [MiDimens.spaceSm]）。
  static const double titleTopGap = 8;

  /// 标题行盒底 -> 次行图片顶（度量墨迹 35px ≈ 15.6dp，扣字形下留白
  /// ≈15dp；行距 15 + 卡高 232.45 = 247.45 ≈ 度量行距 247）。
  static const double rowGap = 15;

  /// 网格列间距（度量 26.5px ≈ 11.8dp，与页边距同量级取 11.9）。
  static const double columnGap = 11.9;

  // ── 悬停快捷操作条（桌面，推导值） ────────────────────────────────────────
  //
  // 参考素材只有触屏手机，没有悬停样张。以下两项是布局常量而非度量值：
  // 取值参照通行的「预览图内嵌操作条」形态（视频卡片 / 文件缩略图）。

  /// 悬停快捷操作条高度 **36**：能容一行 28.3 高的 `MiButton`（度量按钮高）
  /// 加下 4dp 贴边留白，又不至于吃掉太多预览图。
  static const double quickActionsHeight = 36;

  /// 操作条内按钮间距 **8**（= [MiDimens.spaceSm] 档）。
  static const double quickActionsGap = 8;

  /// 操作条滑入时长 180ms `easeOutCubic`（**推导值**：无悬停样张，取通行
  /// 缩略图操作条的快滑档；曲线与页面推入转场同族）。
  static const int quickActionsSlideMs = 180;
}
